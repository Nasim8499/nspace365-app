import puppeteer from 'puppeteer-core';
const URL='https://nspace-six.vercel.app';
const wait=(ms)=>new Promise(r=>setTimeout(r,ms));
const b=await puppeteer.launch({executablePath:'/usr/bin/google-chrome',headless:'new',args:['--no-sandbox','--user-data-dir=/tmp/p'+Date.now()]});
const p=await b.newPage();
await p.setViewport({width:390,height:844,deviceScaleFactor:2,isMobile:true,hasTouch:true});
await p.goto(URL,{waitUntil:'networkidle0'});
await wait(800);
await p.evaluate(()=>document.querySelector('.welc-skip')?.click());
await p.waitForSelector('.authcard');
await p.click('[data-testid="auth-fill-admin"]');
await p.type('[data-testid="auth-password"]','VisaHOBe1323@');
await p.click('[data-testid="auth-submit"]');
await p.waitForSelector('.dashstat',{timeout:20000});
await p.evaluate(()=>{location.hash='#/chat';});
await wait(900);
await p.evaluate(()=>document.querySelector('button[title="New chat"]')?.click());
await wait(600);
await p.evaluate(()=>{document.querySelectorAll('button.conv')[0]?.click();});
await wait(1200);
const ta=await p.$('textarea');
await ta.click();
await p.keyboard.type('Hello there');
await wait(300);
console.log('value after typing:', await p.evaluate(()=>document.querySelector('textarea')?.value));
await p.keyboard.press('Enter');
await wait(3000);
console.log('counts', await p.evaluate(()=>({rows:document.querySelectorAll('.msgrow').length, bubbles:document.querySelectorAll('.bubble').length, conv:JSON.parse(localStorage.getItem('nspace.db.v3')||'{}')?.conversations?.map(c=>c.messages.length)})));
console.log('text', await p.evaluate(()=>document.querySelector('.threadpane')?.innerText.replace(/\s+/g,' ').slice(0,300)));
await p.screenshot({path:'shots/p-chat-after2.png'});
await b.close();
